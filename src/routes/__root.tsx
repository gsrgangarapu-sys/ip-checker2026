import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import {
  Outlet,
  Link,
  createRootRouteWithContext,
  useRouter,
  HeadContent,
  Scripts,
} from "@tanstack/react-router";
import * as React from "react";
import { Helmet, HelmetProvider } from "react-helmet-async";
import ReactGA from "react-ga4";

import appCss from "../styles.css?url";

export const Route = createRootRouteWithContext<{ queryClient: QueryClient }>()({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { name: "theme-color", content: "#071120" },
    ],
    links: [
      { rel: "stylesheet", href: appCss },
      { rel: "icon", type: "image/svg+xml", href: "data:image/svg+xml,<svg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 100 100%22><text y=%22.9em%22 font-size=%2290%22>🛡️</text></svg>" },
      { rel: "preconnect", href: "https://fonts.googleapis.com" },
      { rel: "preconnect", href: "https://fonts.gstatic.com", crossOrigin: "anonymous" },
      {
        rel: "stylesheet",
        href: "https://fonts.googleapis.com/css2?family=Manrope:wght@400;500;600;700;800&family=Space+Grotesk:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;700&display=swap",
      },
    ],
  }),
  shellComponent: RootShell,
  component: RootComponent,
});

function RootShell({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  React.useEffect(() => {
    // Initialize GA4 with a placeholder ID
    ReactGA.initialize("G-XXXXXXXXXX");
    ReactGA.send("pageview");

    const unsubscribe = router.subscribe('onResolved', (event: any) => {
      const path = event.toLocation?.pathname || event.location?.pathname || window.location.pathname;
      ReactGA.send({ hitType: "pageview", page: path });
    });
    return () => unsubscribe();
  }, [router]);

  return (
    <HelmetProvider>
      <QueryClientProvider client={queryClient}>
        <Helmet>
          <title>DNSChecker — Free IP Checker &amp; Network Intelligence Tools</title>
          <meta
            name="description"
            content="Instantly check your public and local IP address, geolocation, ISP, DNS records, SSL certificates, and network security intelligence."
          />
        </Helmet>
        <div className="ambient-glow" />
        <Outlet />
      </QueryClientProvider>
    </HelmetProvider>
  );
}

